const int g_video_mode_count = (int)COUNT_OF(g_video_modes);

static const uint32_t k_clocks_khz[4] = { 28636, 24545, 25175, 21052 };

void video_crtc(uint8_t reg, uint16_t value)
{
    out8(CRTC_ADDRESS, reg);
    out16(CRTC_DATA, value);
}

uint16_t video_register(const video_mode_t* mode, int reg)
{
    if (reg < 2)
        return mode->crtc[reg];

    return reg < 4 ? 0 : mode->crtc[reg - 2];
}

// Stopped first, as the BIOS does, then every register, the layer formats and priority, and START last
void video_program(const video_mode_t* mode)
{
    video_crtc(CRTC_CR0, (uint16_t)(video_register(mode, CRTC_CR0) & ~CRTC_START));

    for (int reg = 0; reg < 32; reg++)
    {
        if (reg != CRTC_CR0 && reg != 2 && reg != 3)
            video_crtc((uint8_t)reg, video_register(mode, reg));
    }

    out8(OUTPUT_ADDRESS, 0x00);
    out8(OUTPUT_DATA, mode->output[0]);
    out8(OUTPUT_ADDRESS, 0x01);
    out8(OUTPUT_DATA, mode->output[1]);
    video_crtc(CRTC_CR0, (uint16_t)(video_register(mode, CRTC_CR0) | CRTC_START));
    out8(VIDEO_STATUS, 0x0F);
}

const video_mode_t* video_find(const char* name)
{
    for (int i = 0; i < g_video_mode_count; i++)
    {
        const char* a = g_video_modes[i].name;
        const char* b = name;

        while (*a != 0 && *a == *b)
        {
            a++;
            b++;
        }

        if (*a == 0 && *b == 0)
            return &g_video_modes[i];
    }

    return 0;
}

uint32_t video_dot_khz(const video_mode_t* mode)
{
    return k_clocks_khz[video_register(mode, CRTC_CR1) & 0x03];
}

// The book's timing: a line is HST + 1 dots at the CR1 clock, the frame VST + 1 half-lines, VSYNC VST2 - VST1
uint32_t video_line_ns(const video_mode_t* mode)
{
    uint32_t dots = (uint32_t)video_register(mode, CRTC_HST) + 1;
    return dots * 1000000u / k_clocks_khz[video_register(mode, CRTC_CR1) & 0x03];
}

uint32_t video_frame_us(const video_mode_t* mode)
{
    return ((uint32_t)video_register(mode, CRTC_VST) + 1) * video_line_ns(mode) / 2000u;
}

uint32_t video_vsync_us(const video_mode_t* mode)
{
    uint32_t half_lines = (uint32_t)(uint16_t)(video_register(mode, CRTC_VST2) - video_register(mode, CRTC_VST1));
    return half_lines * video_line_ns(mode) / 2000u;
}

uint32_t video_hsync_ns(const video_mode_t* mode)
{
    return (uint32_t)video_register(mode, CRTC_HSW1) * 1000000u / k_clocks_khz[video_register(mode, CRTC_CR1) & 0x03];
}

// Polls the status port until the masked bits read the value; the time is taken when they do
int video_wait(uint8_t mask, uint8_t value, uint32_t timeout_us, uint32_t* time)
{
    uint32_t start = tb_now();

    for (uint32_t polls = 0; polls < TIMEOUT_POLLS; polls++)
    {
        if ((in8(VIDEO_STATUS) & mask) == value)
        {
            *time = tb_now();
            return 1;
        }

        if ((polls & 0x3F) == 0 && tb_now() - start > timeout_us)
            break;
    }

    *time = tb_now();
    return VIDEO_TIMEOUT;
}

int video_wait_rise(uint8_t mask, uint32_t timeout_us, uint32_t* time)
{
    return video_wait(mask, 0, timeout_us, time) && video_wait(mask, mask, timeout_us, time);
}

int video_wait_fall(uint8_t mask, uint32_t timeout_us, uint32_t* time)
{
    return video_wait(mask, mask, timeout_us, time) && video_wait(mask, 0, timeout_us, time);
}

// The CPU clock from 32 AAMs a pass, 17 clocks each on the 386 and 15 on the 486, plus DEC and JNZ
uint32_t video_clock_khz(void)
{
    uint32_t pass = g_machine.cpu == CPU_TYPE_486 ? 32 * 15 + 1 + 3 : 32 * 17 + 2 + 8;
    uint32_t start = tb_now();
    video_clock_loop(CLOCK_PASSES);
    uint32_t end = tb_now();
    return end != start ? pass * CLOCK_PASSES * 1000u / (end - start) : 0;
}

// A tight wait for the next rise of bit 0, timed as it's seen
int video_vsync_rise(uint32_t* time)
{
    if (video_wait_bit(VIDEO_VSYNC, 0, WAIT_POLLS) == 0 || video_wait_bit(VIDEO_VSYNC, VIDEO_VSYNC, WAIT_POLLS) == 0)
        return 0;

    *time = tb_now();
    return 1;
}

// How many video_scan polls with this mask take the time given
uint32_t video_scan_polls(uint32_t us, uint32_t mask)
{
    uint32_t changes[8];
    uint32_t start = tb_now();
    uint32_t done = video_scan(CALIBRATION_POLLS, changes, 8, mask);
    uint32_t elapsed = tb_now() - start;
    return elapsed != 0 ? us * done / elapsed : 0;
}

// A poll index of a scan that took elapsed_us over done polls, in ns
int32_t video_poll_ns(int32_t polls, uint32_t elapsed_us, uint32_t done)
{
    uint32_t magnitude = (uint32_t)(polls < 0 ? -polls : polls);
    uint32_t elapsed_ns = elapsed_us * 1000u;

    if (done == 0)
        return 0;

    uint32_t ns = magnitude * (elapsed_ns / done) + magnitude * (elapsed_ns % done) / done;
    return polls < 0 ? -(int32_t)ns : (int32_t)ns;
}

void video_sprite_reg(uint8_t reg, uint8_t value)
{
    out8(VIDEO_SPRITE_INDEX, reg);
    out8(VIDEO_SPRITE_DATA, value);
}

// BUSY polled in chunks, so the time base keeps up through a transfer of any length
int video_sprite_wait(uint8_t value, uint32_t* time)
{
    uint32_t start = tb_now();

    do
    {
        if (video_wait_port(VIDEO_SPRITE_STATUS, VIDEO_SPRITE_BUSY, value, BUSY_CHUNK) != 0)
        {
            *time = tb_now();
            return 1;
        }
    }
    while (tb_now() - start < BUSY_TIMEOUT_US);

    return 0;
}
