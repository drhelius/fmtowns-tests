#!/usr/bin/env python3
"""Writes the C table test 1.2 uses to name the 64 KiB blocks it reads: the CRC-32 of every 64 KiB slice of the
FM Towns ROM files found under a folder, with the file each one comes from. No ROM data goes into the table.

romslices.py <folder> <output.c>

Files are recognized by the CRC-32 of the whole file, wherever they are and whatever their names; files the cloud
hasn't downloaded are skipped instead of fetched.
"""

import os
import stat
import sys
import zlib

SLICE = 0x10000
EXTENSIONS = (".rom", ".m36", ".m37", ".m79")
SIZES = (0x40000, 0x80000, 0x200000)
DATALESS = 0x40000000

# Whole-file CRC: the parts it holds as (short name, type letter, offset, size)
# Type letters: Y system, O OS, E extension, D dictionary, N font, T 20-dot font
KNOWN = {
    0x53319E23: [("M12SYS", "Y", 0, 0x40000)],
    0x112872EE: [("M12DOS", "O", 0, 0x80000)],
    0x955C6B75: [("M12FNT", "N", 0, 0x40000)],
    0xB314C659: [("M12DIC", "D", 0, 0x80000)],
    0x92F3FA67: [("UXSYS", "Y", 0, 0x40000)],
    0x22270E9F: [("UXDOS", "O", 0, 0x80000)],
    0xDD6FD544: [("UXFNT", "N", 0, 0x40000)],
    0x82D1DAA2: [("UXDIC", "D", 0, 0x80000)],
    0x9C0C060C: [("MAROS", "O", 0x000000, 0x80000), ("MAREX0", "E", 0x080000, 0x80000),
                 ("MAREX1", "E", 0x100000, 0x80000), ("MAREX2", "E", 0x180000, 0x80000)],
    0xFB66BB56: [("MAREX3", "E", 0x000000, 0x80000), ("MARF20", "T", 0x080000, 0x80000),
                 ("MARDIC", "D", 0x100000, 0x80000), ("MARFNT", "N", 0x180000, 0x40000),
                 ("MARSYS", "Y", 0x1C0000, 0x40000)],
    0x8AEFF982: [("HRSYS", "Y", 0, 0x40000)],
    0xAFE4EBCF: [("V10SYS", "Y", 0, 0x40000)],
    0x9F55A20C: [("V10F20", "T", 0, 0x80000)],
    0x74B1D152: [("V03DIC", "D", 0, 0x80000)],
    0x0108A090: [("V03FNT", "N", 0, 0x40000)],
    0xF3FC636E: [("MXM79", "Y", 0, 0x200000)],
}


def find_files(root):
    found = {}

    for folder, _, names in os.walk(root):
        for name in names:
            if not name.lower().endswith(EXTENSIONS):
                continue

            path = os.path.join(folder, name)
            info = os.stat(path)

            if not stat.S_ISREG(info.st_mode) or info.st_size not in SIZES:
                continue

            if getattr(info, "st_flags", 0) & DATALESS:
                print("not downloaded, skipped: %s" % path)
                continue

            with open(path, "rb") as f:
                data = f.read()

            crc = zlib.crc32(data) & 0xFFFFFFFF

            if crc in KNOWN and crc not in found:
                found[crc] = data

    return found


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1

    found = find_files(sys.argv[1])
    names = []
    slices = []

    for crc in KNOWN:
        if crc not in found:
            print("not found: %08X (%s)" % (crc, ", ".join(part[0] for part in KNOWN[crc])))
            continue

        for name, kind, offset, size in KNOWN[crc]:
            data = found[crc][offset:offset + size]
            index = len(names)
            names.append((name, kind, zlib.crc32(data) & 0xFFFFFFFF, size // SLICE))

            for i in range(size // SLICE):
                slices.append((zlib.crc32(data[i * SLICE:(i + 1) * SLICE]) & 0xFFFFFFFF, index, i))

    slices.sort()

    with open(sys.argv[2], "w") as out:
        out.write("// Generated by tools/romslices.py from the CRC-32 of every 64 KiB slice of the known ROM files,\n")
        out.write("// sorted by CRC, file and slice\n\n")
        out.write('#include "rom_slices.h"\n\n')
        out.write("const rom_file_t g_rom_files[ROM_FILE_COUNT] =\n{\n")

        for name, kind, crc, count in names:
            out.write('    { "%s", \'%s\', %u, 0x%08Xu },\n' % (name, kind, count, crc))

        out.write("};\n\nconst rom_slice_t g_rom_slices[ROM_SLICE_COUNT] =\n{\n")

        for i in range(0, len(slices), 3):
            line = ", ".join("{ 0x%08Xu, %u, %u }" % s for s in slices[i:i + 3])
            out.write("    %s%s\n" % (line, "," if i + 3 < len(slices) else ""))

        out.write("};\n")

    header = os.path.join(os.path.dirname(sys.argv[2]), "rom_slices.h")

    with open(header, "w") as out:
        out.write("#ifndef ROM_SLICES_H\n#define ROM_SLICES_H\n\n#include <stdint.h>\n\n")
        out.write("// Generated by tools/romslices.py\n\n")
        out.write("#define ROM_FILE_COUNT %u\n#define ROM_SLICE_COUNT %u\n\n" % (len(names), len(slices)))
        out.write("typedef struct\n{\n    const char* name;\n    char kind;\n    uint8_t slices;\n    uint32_t crc;\n"
                  "} rom_file_t;\n\n")
        out.write("typedef struct\n{\n    uint32_t crc;\n    uint8_t file;\n    uint8_t slice;\n} rom_slice_t;\n\n")
        out.write("extern const rom_file_t g_rom_files[ROM_FILE_COUNT];\n")
        out.write("extern const rom_slice_t g_rom_slices[ROM_SLICE_COUNT];\n\n#endif /* ROM_SLICES_H */\n")

    print("%u files, %u slices" % (len(names), len(slices)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
